    private void loadPets() {

    cmbSelectPet.removeAllItems();

    String sql =
            "SELECT pet_id, pet_name " +
            "FROM tbl_pet " +
            "WHERE user_id = ? " +
            "ORDER BY pet_name ASC";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setInt(1, UserSession.getUserId());

        ResultSet rs = pst.executeQuery();

        while (rs.next()) {

            cmbSelectPet.addItem(
                    rs.getInt("pet_id") + " - " + rs.getString("pet_name")
            );
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Unable to load your pets.\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
}

    private void loadUserPetsIntoComboBox() {
    cmbSelectPet.removeAllItems(); // Replace with your actual combo box variable name if different
    
    String query = "SELECT pet_id, pet_name FROM tbl_pet WHERE user_id = ?";
    
    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        pstmt.setInt(1, UserSession.getUserId());
        
        try (ResultSet rs = pstmt.executeQuery()) {
            while (rs.next()) {
                int petId = rs.getInt("pet_id");
                String petName = rs.getString("pet_name");
                
                // Format display as "ID - PetName" so we can easily parse the ID later
                cmbSelectPet.addItem(petId + " - " + petName);
            }
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error loading pets: " + e.getMessage());
    }
}
    
