    private void btnConfirmAppointmentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmAppointmentActionPerformed
// 1. Get selected pet item from ComboBox
String selectedItem = (String) cmbSelectPet.getSelectedItem();
    if (selectedItem == null || selectedItem.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a pet.", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    int petId = Integer.parseInt(selectedItem.split(" - ")[0]);
    
    // 2. Get form values
    String serviceType = (String) cmbService.getSelectedItem();
    String appointmentTime = (String) cmbTime.getSelectedItem();
    
    // Get date from JDateChooser
    java.util.Date selectedDate = jDateChooser1.getDate();
    if (selectedDate == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an appointment date.", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    java.text.SimpleDateFormat dateFormat = new java.text.SimpleDateFormat("yyyy-MM-dd");
    String appointmentDate = dateFormat.format(selectedDate);
    
    // 3. Get and validate Reason for Visit
    String reasonForVisit = Reason.getText().trim(); // Adjust variable name if different
    if (reasonForVisit.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter a reason for the visit.", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        Reason.requestFocus(); // Focuses cursor on the text box
        return;
    }
    
    // 4. Get amount using your service method
    double amount = getServiceAmount(serviceType);
    
    // 5. Check if time slot is occupied
    String checkQuery = "SELECT COUNT(*) AS booked FROM tbl_appointments WHERE appointment_date = ? AND appointment_time = ?";
    
    try (Connection conn = DBConnection.getConnection();
         PreparedStatement checkStmt = conn.prepareStatement(checkQuery)) {
        
        checkStmt.setString(1, appointmentDate);
        checkStmt.setString(2, appointmentTime);
        
        try (ResultSet rs = checkStmt.executeQuery()) {
            if (rs.next() && rs.getInt("booked") > 0) {
                javax.swing.JOptionPane.showMessageDialog(
                    this, 
                    "Sorry! The time slot " + appointmentTime + " on " + appointmentDate + " is already occupied.", 
                    "Time Slot Occupied", 
                    javax.swing.JOptionPane.WARNING_MESSAGE
                );
                return;
            }
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        return;
    }
    
    // 6. Insert into tbl_appointments including the reason_for_visit
    String insertQuery = "INSERT INTO tbl_appointments (pet_id, service_type, appointment_date, appointment_time, amount, status, reason_for_visit) VALUES (?, ?, ?, ?, ?, ?, ?)";
    
    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(insertQuery)) {
        
        pstmt.setInt(1, petId);
        pstmt.setString(2, serviceType);
        pstmt.setString(3, appointmentDate);
        pstmt.setString(4, appointmentTime);
        pstmt.setDouble(5, amount);
        pstmt.setString(6, "Pending");
        pstmt.setString(7, reasonForVisit);
        
        int rowsInserted = pstmt.executeUpdate();
        if (rowsInserted > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Appointment booked successfully!");
            
            new Homepage(UserSession.getUserId()).setVisible(true);
            this.dispose();
        }
        
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnConfirmAppointmentActionPerformed

