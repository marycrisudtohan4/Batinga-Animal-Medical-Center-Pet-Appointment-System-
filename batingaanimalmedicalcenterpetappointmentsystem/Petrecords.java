 private void loadUserPets() {
    cmbSelectPet.removeAllItems();
    String query = "SELECT pet_id, pet_name FROM tbl_pet WHERE user_id = ?";
    
    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        pstmt.setInt(1, UserSession.getUserId());
        try (ResultSet rs = pstmt.executeQuery()) {
            while (rs.next()) {
                int petId = rs.getInt("pet_id");
                String petName = rs.getString("pet_name");
                cmbSelectPet.addItem(petId + " - " + petName);
            }
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error loading pets: " + e.getMessage());
    }
}
 
 private void loadPetMedicalHistory() {
    String selectedItem = (String) cmbSelectPet.getSelectedItem();
    if (selectedItem == null || selectedItem.isEmpty()) {
        return;
    }
    
    // Extract pet_id from the dropdown string (e.g., "22 - Clintoy" -> 22)
    int petId = Integer.parseInt(selectedItem.split(" - ")[0]);
    
    DefaultTableModel model = (DefaultTableModel) tblMedicalHistory.getModel();
    model.setRowCount(0); // Clear old table rows
    
    // Query matching your exact columns in phpMyAdmin
    String query = "SELECT appointment_date, diagnosis, treatment, veterinarian FROM tbl_medical_history WHERE pet_id = ? ORDER BY appointment_date DESC";
    
    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        pstmt.setInt(1, petId);
        try (ResultSet rs = pstmt.executeQuery()) {
            while (rs.next()) {
                String date = rs.getString("appointment_date");
                String diagnosis = rs.getString("diagnosis");
                String treatment = rs.getString("treatment");
                String vet = rs.getString("veterinarian");
                
                // Adds row matching your table view: Date, Diagnosis, Treatment, Veterinarian
                model.addRow(new Object[]{date, diagnosis, treatment, vet});
            }
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error loading pet records: " + e.getMessage());
        e.printStackTrace();
    }
}
    
 
  
