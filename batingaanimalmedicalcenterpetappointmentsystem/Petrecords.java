    private void cmbSelectPetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbSelectPetActionPerformed
        String selectedItem = cmbSelectPet.getSelectedItem().toString();
    String petId = selectedItem.split(" - ")[0].trim(); // Gets the number before the dash

    // Clear existing table rows
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblMedicalHistory.getModel();
    model.setRowCount(0);

    // Query tbl_visit_records for this pet
    String sql = "SELECT visit_date, diagnosis, treatment, veterinarian FROM tbl_visit_records WHERE pet_id = ?";

    try (java.sql.Connection con = DBConnection.getConnection();
         java.sql.PreparedStatement pst = con.prepareStatement(sql)) {
        
        pst.setString(1, petId);
        try (java.sql.ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                String date = rs.getString("visit_date");
                String diagnosis = rs.getString("diagnosis");
                String treatment = rs.getString("treatment");
                String veterinarian = rs.getString("veterinarian");

                // Add row to your table
                model.addRow(new Object[]{date, diagnosis, treatment, veterinarian});
            }
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error loading pet records: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_cmbSelectPetActionPerformed

